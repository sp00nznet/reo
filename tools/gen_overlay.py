"""Recompile one MWo3 overlay from the disc into recomp/config/output_ovl_<prefix>/.

    py -3 tools/gen_overlay.py <DAT> <prefix> [<outdir>]
    py -3 tools/gen_overlay.py game_data/BIN/2.DAT game

Steps: decode the container to a text-only ELF (tools/ps2_debug/mwo3.py), run ps2_recomp on it,
prefix every function the overlay defines with <prefix>_ (overlays share load addresses, so
their sub_<addr> names collide), rename the generated headers to <prefix>_recompiled_*.h, and
turn the function table into a ReoOverlay table that registers itself with recomp/reo_overlays.
See docs/mwo3-overlay-format.md.
"""
import os, re, shutil, struct, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'tools', 'ps2_debug'))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
RECOMP = os.path.join(ROOT, 'third_party', 'PS2Recomp', 'out', 'build-upstream',
                      'ps2xRecomp', 'Release', 'ps2_recomp.exe')
ENTRY = re.compile(r'g_ps2RecompiledFunctionTable\[\d+\] = (\w+); // (0x[0-9a-fA-F]+)')

CONFIG = '''thread_entries = [{entries}]
function_starts = [{splits}]

[general]
input = "{elf}"
ghidra_output = ""
output = "{raw}/"
single_file_output = false
patch_syscalls = false
patch_cop0 = true
patch_cache = true
stubs = []
skip = []
'''

JR_RA = 0x03E00008


def ends(word):
    """jr ra or j: control never falls through past its delay slot."""
    return word == JR_RA or word >> 26 == 2
ELF = os.path.join(ROOT, 'game_data', 'SLUS_207.65')


def function_starts(text, base, data_words):
    """Entry points the recompiler cannot find by itself.

    Base code reaches overlay functions through pointer tables, so nothing inside the
    overlay JALs to them and they get folded into the preceding function with no entry
    of their own. A function start is the first instruction after a `jr ra` or a `j`
    (a tail-call thunk ends that way), its delay slot and any nop padding; keep it when
    it is a stack-frame prologue
    (`addiu sp,sp,-N`), a `j` thunk, or when some data word points at it (leaf functions).
    """
    words = struct.unpack_from('<%dI' % (len(text) // 4), text)
    pointed = set(data_words)
    starts = []
    for i, w in enumerate(words):
        if w == 0:
            continue
        j = i - 1
        while j >= 0 and words[j] == 0:
            j -= 1
        # skipping nops lands on the delay slot, or on the jump itself when the slot was a nop
        boundary = j < 0 or ends(words[j]) or (j >= 1 and ends(words[j - 1]))
        prologue = (w >> 16) == 0x27BD and (w & 0x8000)
        thunk = w >> 26 == 2  # `j target` tail-call thunk, reached through pointers we cannot see
        if boundary and (prologue or thunk or base + i * 4 in pointed):
            starts.append(base + i * 4)
    return starts


def prologues(text, base, addresses):
    """The addresses whose first instruction is a stack-frame prologue (addiu sp,sp,-N)."""
    out = []
    for a in addresses:
        w, = struct.unpack_from('<I', text, a - base)
        if (w >> 16) == 0x27BD and (w & 0x8000):
            out.append(a)
    return out


def data_words(*blobs):
    out = []
    for blob in blobs:
        out.extend(struct.unpack_from('<%dI' % (len(blob) // 4), blob))
    return out


def register_source(table_cpp, prefix, header):
    rows = ENTRY.findall(table_cpp)
    body = ''.join('    {%su, %s_%s},\n' % (a, prefix, sym) for sym, a in rows)
    return ('#include "../../reo_overlays.h" // recomp/reo_overlays.h\n'
            '#include "%s_recompiled_functions.h"\n\n'
            '// Generated by tools/gen_overlay.py from %s.\n'
            'static const ReoOverlayEntry kEntries[] = {\n%s};\n\n'
            'static const ReoOverlay kOverlay{"%s", 0x%Xu, 0x%Xu, kEntries,\n'
            '                                 sizeof(kEntries) / sizeof(kEntries[0])};\n'
            'static const ReoOverlayRegistrar kRegistrar(kOverlay);\n'
            ) % (prefix, header['name'], body, header['name'], header['addr'], header['end']), len(rows)


def convert(raw, out, prefix, header):
    os.makedirs(out, exist_ok=True)
    up = prefix.upper()
    table = open(os.path.join(raw, 'register_functions.cpp')).read()
    own = set(sym for sym, _ in ENTRY.findall(table))
    # Every sub_<addr> this overlay defines gets the prefix; names of other code are untouched.
    rename = re.compile(r'\bsub_[0-9A-F]{8}_0x[0-9a-f]+\b')
    for name in os.listdir(raw):
        src = os.path.join(raw, name)
        if name == 'register_functions.cpp':
            text, n = register_source(table, prefix, header)
            open(os.path.join(out, prefix + '_register.cpp'), 'w').write(text)
            print('%s (%s): %d entry points' % (prefix, header['name'], n))
            continue
        text = open(src).read().replace('ps2_recompiled_', prefix + '_recompiled_') \
                                .replace('PS2_RECOMPILED_', up + '_RECOMPILED_')
        text = rename.sub(lambda m: prefix + '_' + m.group(0) if m.group(0) in own else m.group(0), text)
        dst = name.replace('ps2_recompiled_', prefix + '_recompiled_')
        open(os.path.join(out, prefix + '_' + dst if dst.startswith('sub_') else dst), 'w').write(text)


def main(dat, prefix, out=None):
    out = out or os.path.join(ROOT, 'recomp', 'config', 'output_ovl_' + prefix)
    import mwo3
    from dump_overlays import create_overlay_elf
    work = os.path.join(ROOT, 'scratch', 'overlay_' + prefix)
    raw = os.path.join(work, 'raw')
    shutil.rmtree(work, ignore_errors=True)
    os.makedirs(raw)
    img, h = mwo3.load(dat)
    elf = os.path.join(work, prefix + '.elf')
    # text only: the data section decoded as code gives a runaway function
    create_overlay_elf(img[0x40:0x40 + h['text']], h['addr'] + 0x40, elf)
    text = img[0x40:0x40 + h['text']]
    elf_bytes = open(ELF, 'rb').read()
    lo, hi = h['addr'] + 0x40, h['addr'] + 0x40 + h['text']
    starts = set(function_starts(text, lo, data_words(img[0x40:], elf_bytes)))
    # Calls from the base ELF and from the other overlays are function starts too.
    from gen_base_config import OVERLAYS, base_text_range, call_targets
    blo, bhi, boff = base_text_range(elf_bytes)
    calls = call_targets(elf_bytes[boff:boff + bhi - blo])
    for i in OVERLAYS:
        other, oh = mwo3.load(os.path.join(ROOT, 'game_data', 'BIN', '%d.DAT' % i))
        calls |= call_targets(other[0x40:0x40 + oh['text']])
    starts |= {t for t in calls if lo <= t < hi}
    entries = ', '.join('"0x%08X"' % a for a in sorted(starts))
    # Prologues also cut the function they sit in: as mere entry labels they leave whole
    # runs of pointer-table functions folded into one host function deep enough to blow
    # the host stack (game.bin 0x69DB40 spanned 36 KB). Pointed-at leaves stay labels,
    # since a jump-table case label is pointed at too and must not be split off.
    splits = ', '.join('"0x%08X"' % a for a in sorted(prologues(text, lo, starts)))
    cfg = os.path.join(work, 'config.toml')
    open(cfg, 'w').write(CONFIG.format(elf=elf.replace('\\', '/'), raw=raw.replace('\\', '/'), entries=entries,
                                       splits=splits))
    subprocess.run([RECOMP, cfg], check=True, stdout=subprocess.DEVNULL)
    shutil.rmtree(out, ignore_errors=True)
    convert(raw, out, prefix, h)


def _selfcheck():
    t = ('        g_ps2RecompiledFunctionTable[0] = sub_00370000_0x370000; // 0x370000\n'
         '        g_ps2RecompiledFunctionTable[65] = sub_00370000_0x370000; // 0x370104\n')
    text, n = register_source(t, 'submain', dict(name='submain.bin', addr=0x370000, end=0x38cd80))
    assert n == 2 and '{0x370104u, submain_sub_00370000_0x370000},' in text, text
    assert 'kOverlay{"submain.bin", 0x370000u, 0x38CD80u' in text, text
    # jr ra / delay / nop, then a prologue and a pointed-at leaf; a mid-function addiu is not a start
    code = struct.pack('<8I', 0x27BDFFF0, JR_RA, 0, 0, 0x27BDFFE0, JR_RA, 0, 0x24020001)
    assert function_starts(code, 0x1000, [0x101C]) == [0x1000, 0x1010, 0x101C]
    assert function_starts(code, 0x1000, []) == [0x1000, 0x1010]
    # a prologue after a j thunk (submain.bin 0x373380 follows `j 0x372780`)
    code = struct.pack('<4I', 0x080DC9E0, 0, 0, 0x27BDFF70)
    assert function_starts(code, 0x2000, []) == [0x2000, 0x200C]
    assert prologues(code, 0x2000, [0x2000, 0x200C]) == [0x200C]


if __name__ == '__main__':
    _selfcheck()
    if len(sys.argv) not in (3, 4):
        sys.exit(__doc__)
    main(*sys.argv[1:])
