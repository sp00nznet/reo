"""Recompile one MWo3 overlay from the disc into recomp/config/output_<name>/.

    py -3 tools/gen_overlay.py <DAT> <prefix> <register_fn> <outdir>
    py -3 tools/gen_overlay.py game_data/BIN/0.DAT overlay registerOverlayFunctions recomp/config/output_overlay

Steps: decode the container to a text-only ELF (tools/ps2_debug/mwo3.py), run ps2_recomp on it,
then rename the generated headers to <prefix>_recompiled_*.h and turn the dense function table
into PS2Runtime::registerFunction calls. Overlays sit outside the main table, so the runtime
keeps them in its overflow map. See docs/mwo3-overlay-format.md.
"""
import os, re, shutil, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'tools', 'ps2_debug'))
RECOMP = os.path.join(ROOT, 'third_party', 'PS2Recomp', 'out', 'build-upstream',
                      'ps2xRecomp', 'Release', 'ps2_recomp.exe')
ENTRY = re.compile(r'g_ps2RecompiledFunctionTable\[\d+\] = (\w+); // (0x[0-9a-fA-F]+)')

CONFIG = '''[general]
input = "{elf}"
ghidra_output = ""
output = "{raw}/"
single_file_output = false
patch_syscalls = false
patch_cop0 = true
patch_cache = true
stubs = []
skip = []
'''


def register_source(table_cpp, prefix, fn):
    rows = ENTRY.findall(table_cpp)
    body = ''.join('    runtime.registerFunction(%su, %s);\n' % (a, s) for s, a in rows)
    return ('#include "ps2_runtime.h"\n#include "%s_recompiled_functions.h"\n\n'
            '// Generated by tools/gen_overlay.py. Overlay functions live outside the main\n'
            '// function table, so they go into PS2Runtime\'s overflow map.\n'
            'void %s(PS2Runtime &runtime)\n{\n%s}\n') % (prefix, fn, body), len(rows)


def convert(raw, out, prefix, fn):
    os.makedirs(out, exist_ok=True)
    up = prefix.upper()
    for name in os.listdir(raw):
        src = os.path.join(raw, name)
        if name == 'register_functions.cpp':
            text, n = register_source(open(src).read(), prefix, fn)
            open(os.path.join(out, prefix + '_register.cpp'), 'w').write(text)
            print('%s: %d entry points' % (fn, n))
            continue
        text = open(src).read().replace('ps2_recompiled_', prefix + '_recompiled_') \
                                .replace('PS2_RECOMPILED_', up + '_RECOMPILED_')
        open(os.path.join(out, name.replace('ps2_recompiled_', prefix + '_recompiled_')), 'w').write(text)


def main(dat, prefix, fn, out):
    import mwo3
    from dump_overlays import create_overlay_elf
    work = os.path.join(ROOT, 'scratch', 'overlay_' + prefix)
    raw = os.path.join(work, 'raw')
    shutil.rmtree(work, ignore_errors=True)
    os.makedirs(raw)
    img, h = mwo3.load(dat)
    elf = os.path.join(work, prefix + '.elf')
    # text only: the data section decoded as code gives a runaway function
    create_overlay_elf(img[0x40:0x40 + h['text']], h['addr'] + 0x40, elf)
    cfg = os.path.join(work, 'config.toml')
    open(cfg, 'w').write(CONFIG.format(elf=elf.replace('\\', '/'), raw=raw.replace('\\', '/')))
    subprocess.run([RECOMP, cfg], check=True, stdout=subprocess.DEVNULL)
    shutil.rmtree(out, ignore_errors=True)
    convert(raw, out, prefix, fn)


def _selfcheck():
    t = ('        g_ps2RecompiledFunctionTable[0] = sub_00370000_0x370000; // 0x370000\n'
         '        g_ps2RecompiledFunctionTable[65] = sub_00370000_0x370000; // 0x370104\n')
    text, n = register_source(t, 'overlay', 'registerOverlayFunctions')
    assert n == 2 and 'runtime.registerFunction(0x370104u, sub_00370000_0x370000);' in text, text


if __name__ == '__main__':
    _selfcheck()
    if len(sys.argv) != 5:
        sys.exit(__doc__)
    main(*sys.argv[1:])
